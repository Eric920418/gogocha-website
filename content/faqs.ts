/** 取某分類的 FAQ 子集（供 /pricing、/routes 顯示部分題目並注入對應 FAQPage schema）。 */
export const faqsByCategory = (category: FaqCategory): FaqItem[] =>
  faqs.filter((f) => f.category === category);

/** 依題目文字精準取題（供跨分類挑選特定題，如路線頁要的 OD 車資題）。 */
export const faqsByQuestion = (questions: string[]): FaqItem[] =>
  questions
    .map((q) => faqs.find((f) => f.question === q))
    .filter((f): f is FaqItem => f !== undefined);
